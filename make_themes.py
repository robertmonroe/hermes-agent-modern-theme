"""Build Hermes Agent dashboard themes: one shared style (style.css) x every palette (palettes.json).

    python make_themes.py                      # build all themes into ./themes
    python make_themes.py --install            # build, then copy all into your Hermes dashboard-themes folder
    python make_themes.py --install slate zinc # build, then install only these

Hermes looks for themes in a dashboard-themes folder next to the config.yaml that `hermes config path` prints.
Pick one from the theme switcher at the bottom of the dashboard sidebar.
"""
import argparse
import json
import os
import shutil
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
FONT_URL = ("https://fonts.googleapis.com/css2?family=Geist:wght@400;500;600;700"
            "&family=Geist+Mono:wght@400;500&display=swap")
CSS_CAP = 32 * 1024  # Hermes ignores customCSS beyond 32 KiB


def mix(a: str, b: str, t: float) -> str:
    """Blend hex color a toward b by t (0 = a, 1 = b) in sRGB."""
    ca = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    cb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(ca, cb))


def gray_roles(s: dict) -> dict:
    """A gray palette: its darkest shades for surfaces, its lightest for text."""
    return {"bg": s["950"], "card": s["900"], "surface": s["800"], "fg": s["50"],
            "muted": s["400"], "ring": s["500"], "primary": s["200"], "primary_fg": s["900"]}


def color_roles(s: dict) -> dict:
    """A colored palette: near-black surfaces tinted with the color, the color as accent."""
    return {"bg": mix(s["950"], "#0a0a0a", 0.70), "card": mix(s["950"], "#141414", 0.50),
            "surface": mix(s["900"], "#262626", 0.55), "fg": s["50"],
            "muted": mix(s["300"], "#a3a3a3", 0.60),  # tinted gray, not full-strength color
            "ring": s["500"], "primary": s["400"], "primary_fg": s["950"]}


def palettes() -> dict:
    data = json.loads((HERE / "palettes.json").read_text(encoding="utf-8"))
    out = {name: gray_roles(s) for name, s in data["grays"].items()}
    out.update({name: color_roles(s) for name, s in data["colors"].items()})
    return out


def theme_yaml(name: str, c: dict, css: str) -> str:
    root = (
        ":root {\n"
        f"  --sh-bg: {c['bg']};\n  --sh-card: {c['card']};\n  --sh-surface: {c['surface']};\n"
        f"  --sh-fg: {c['fg']};\n  --sh-muted: {c['muted']};\n  --sh-ring: {c['ring']};\n"
        f"  --sh-primary: {c['primary']};\n  --sh-primary-fg: {c['primary_fg']};\n"
        "  --sh-border: rgba(255, 255, 255, 0.10);\n  --sh-input: rgba(255, 255, 255, 0.15);\n"
        "}\n"
    )
    custom_css = "\n".join(("  " + line) if line else "" for line in (root + css).splitlines())
    label = name.capitalize()
    return f"""# Hermes Agent Modern Theme: {label}
# Generated by make_themes.py. Edit style.css / palettes.json and rebuild instead of editing this file.
name: modern-{name}
label: Modern {label}
description: Modern flat style, {name} palette

palette:
  background: "{c['bg']}"
  midground: "{c['fg']}"
  foreground: {{ hex: "{c['primary']}", alpha: 0 }}
  warmGlow: "rgba(0, 0, 0, 0)"
  noiseOpacity: 0

typography:
  fontUrl: "{FONT_URL}"
  fontSans: "'Geist', ui-sans-serif, system-ui, -apple-system, 'Segoe UI', sans-serif"
  fontMono: "'Geist Mono', ui-monospace, 'Cascadia Mono', Consolas, monospace"
  fontDisplay: "'Geist', ui-sans-serif, system-ui, sans-serif"
  baseSize: "14px"
  lineHeight: "1.5"
  letterSpacing: "0"

layout:
  radius: "0.625rem"
  density: comfortable

colorOverrides:
  card: "{c['card']}"
  cardForeground: "{c['fg']}"
  popover: "{c['card']}"
  popoverForeground: "{c['fg']}"
  primary: "{c['primary']}"
  primaryForeground: "{c['primary_fg']}"
  secondary: "{c['surface']}"
  secondaryForeground: "{c['fg']}"
  muted: "{c['surface']}"
  mutedForeground: "{c['muted']}"
  accent: "{c['surface']}"
  accentForeground: "{c['fg']}"
  destructive: "#ff6467"
  destructiveForeground: "{c['fg']}"
  success: "#4ade80"
  warning: "#fbbf24"
  border: "rgba(255, 255, 255, 0.10)"
  input: "rgba(255, 255, 255, 0.15)"
  ring: "{c['ring']}"

customCSS: |
{custom_css}
"""


def hermes_home() -> Path:
    """Ask Hermes where its config lives; fall back to HERMES_HOME, then ~/.hermes."""
    try:
        out = subprocess.run(["hermes", "config", "path"], capture_output=True, text=True,
                             timeout=60, shell=(os.name == "nt")).stdout.strip().splitlines()
        if out and out[-1].endswith("config.yaml"):
            return Path(out[-1]).parent
    except (OSError, subprocess.SubprocessError):
        pass
    env = os.environ.get("HERMES_HOME")
    return Path(env) if env else Path.home() / ".hermes"


def main() -> None:
    ap = argparse.ArgumentParser(description="Build Hermes Agent Modern dashboard themes.")
    ap.add_argument("--out", type=Path, default=HERE / "themes", help="build folder (default: ./themes)")
    ap.add_argument("--install", nargs="*", metavar="PALETTE",
                    help="copy themes into <HERMES_HOME>/dashboard-themes; name palettes to install only those")
    args = ap.parse_args()

    css = (HERE / "style.css").read_text(encoding="utf-8")
    all_palettes = palettes()
    args.out.mkdir(parents=True, exist_ok=True)
    for name, colors in all_palettes.items():
        text = theme_yaml(name, colors, css)
        if len(text.encode("utf-8")) > CSS_CAP:
            raise SystemExit(f"modern-{name}: theme exceeds Hermes' 32 KiB customCSS cap")
        (args.out / f"modern-{name}.yaml").write_text(text, encoding="utf-8")
    print(f"built {len(all_palettes)} themes in {args.out}")

    if args.install is not None:
        wanted = args.install or list(all_palettes)
        unknown = [n for n in wanted if n not in all_palettes]
        if unknown:
            raise SystemExit(f"unknown palette(s): {', '.join(unknown)}")
        dest = hermes_home() / "dashboard-themes"
        dest.mkdir(parents=True, exist_ok=True)
        for name in wanted:
            shutil.copy2(args.out / f"modern-{name}.yaml", dest / f"modern-{name}.yaml")
        print(f"installed {len(wanted)} theme(s) into {dest}")


if __name__ == "__main__":
    main()
